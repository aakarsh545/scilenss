import assert from "node:assert/strict"
import { cameraBasis, project, unproject, panCamera, rotateCamera, zoomCamera, createCamera } from "./orbit-camera.js"

const near = (a, b) => assert.ok(Math.abs(a - b) < 1e-10, `${a} vs ${b}`)
const camera = createCamera()
const viewport = { width: 900, height: 700 }
const basis = cameraBasis(camera)
for (const vector of [basis.right, basis.up, basis.eye]) near(Math.hypot(...vector), 1)
near(basis.right.reduce((sum, value, i) => sum + value * basis.up[i], 0), 0)
const screen = project([4, 3, 2], camera, viewport)
const restored = unproject(screen.x, screen.y, camera, viewport, screen.depth)
restored.forEach((value, i) => near(value, [4, 3, 2][i]))
const before = project([4, 0, 0], camera, viewport)
rotateCamera(camera, 0.4, -0.2)
const after = project([4, 0, 0], camera, viewport)
assert.ok(Math.hypot(after.x - before.x, after.y - before.y) > 5)
const anchor = unproject(500, 300, camera, viewport)
zoomCamera(camera, 0.7, 500, 300, viewport)
const anchored = project(anchor, camera, viewport)
near(anchored.x, 500)
near(anchored.y, 300)
const oldCenter = project([0, 0, 0], camera, viewport)
panCamera(camera, 30, -20)
const newCenter = project([0, 0, 0], camera, viewport)
near(newCenter.x - oldCenter.x, 30)
near(newCenter.y - oldCenter.y, -20)
zoomCamera(camera, 0.6, 650, 250, viewport)
const pivot = project([0, 0, 0], camera, viewport)
rotateCamera(camera, Math.PI / 2, 0.3)
const rotatedPivot = project([0, 0, 0], camera, viewport)
near(rotatedPivot.x, pivot.x)
near(rotatedPivot.y, pivot.y)
rotateCamera(camera, 0, 100)
assert.ok(camera.elevation < Math.PI / 2)
const insetCamera = createCamera()
const inset = { width: 900, height: 700, centerX: 450, centerY: 250 }
near(project([0, 0, 0], insetCamera, inset).y, 250)
const insetPoint = project([3, 2, 1], insetCamera, inset)
unproject(insetPoint.x, insetPoint.y, insetCamera, inset, insetPoint.depth).forEach((value, i) => near(value, [3, 2, 1][i]))
console.log("All 3D camera checks passed")
